"""Per-role evaluation.

These checks use validation résumés and keep the test split untouched.
The Critic check measures agreement with rule labels.
"""
import argparse
import csv
import json
import os
from pathlib import Path
import random
from unittest.mock import patch

from hiremind import config, tools
from hiremind.memory import Memory
from hiremind.roles import critic, searcher
from hiremind.schemas import Profile, Step
from hiremind.skills import extract_skills


def _read_jsonl(path: Path):
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                yield json.loads(line)


