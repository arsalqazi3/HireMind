def eval_critic(cases: list[tuple[Profile, str, float]]) -> dict:
    """Compare scores with weak labels while counting invalid model output."""
    errors = []
    for profile, job_id, expected in cases:
        job = tools.get_job_details(job_id)
        judgments = critic.judge(profile, [job])
        if judgments:
            errors.append(abs(judgments[0].score - expected))
    return {"pairs": len(cases), "valid_scores": len(errors),
            "mae_against_weak_labels": round(sum(errors) / len(errors), 3) if errors else None}


def eval_searcher(profiles: list[Profile]) -> dict:
    """Check action validity and stop decisions after identical real tool results."""
    valid_search = valid_followup = stopped = 0
    for profile in profiles:
        memory = Memory(semantic=profile)
        try:
            action, _ = searcher.next_action(memory)
            valid_search += int(action == "search_jobs")
        except ValueError:
            # Malformed actions count against the model on this check.
            pass
        query = searcher.profile_queries(profile)[0]
        jobs = tools.shortlist_jobs(query, profile)
        memory.episodic.queries.append(query)
        memory.short_term.append(Step(
            state={}, action="search_jobs", args={"query": query},
            result=[{"job_id": job.job_id, "title": job.title} for job in jobs],
        ))
        try:
            action, _ = searcher.next_action(memory)
            valid_followup += 1
            stopped += int(action == "stop")
        except ValueError:
            pass
    return {"profiles": len(profiles), "valid_initial_search": valid_search,
            "valid_followup": valid_followup, "stopped_after_search": stopped}


def main():
    cli = argparse.ArgumentParser(description="Evaluate model output on validation résumés.")
    cli.add_argument("--role", choices=("searcher", "critic"), default="searcher")
    cli.add_argument("--adapter", type=Path)
    cli.add_argument("--exclude-traces", type=Path)
    cli.add_argument("--critic-labels", type=Path, help="Validation JSONL generated by make_pilot_critic_labels")
    cli.add_argument("--limit", type=int, default=12)
    args = cli.parse_args()
    if args.limit < 1:
        cli.error("--limit must be positive")
    if args.adapter and not args.exclude_traces:
        cli.error("--exclude-traces must point to the adapter's train/validation data directory")
    if args.role == "critic" and not args.critic_labels:
        cli.error("--critic-labels is required for a Critic evaluation")
    excluded = set()
    if args.exclude_traces:
        for split in ("train", "val"):
            path = args.exclude_traces / f"{split}.jsonl"
            excluded.update(row["resume_id"] for row in _read_jsonl(path))
    val_ids = set((config.SPLITS_DIR / "val.txt").read_text().splitlines()) - excluded
    with (config.PROCESSED_DIR / "resumes.csv").open(encoding="utf-8", newline="") as handle:
        candidates = [row for row in csv.DictReader(handle) if row["id"] in val_ids]
    if not candidates:
        cli.error("No independent validation résumés are available")
    rng = random.Random(config.SEED)
    if args.role == "searcher":
        sample = rng.sample(candidates, min(args.limit, len(candidates)))
        profiles = [Profile(row["category"], skills=extract_skills(row["text"])) for row in sample]
    else:
        resumes = {row["id"]: row for row in candidates}
        labels = [label for label in _read_jsonl(args.critic_labels) if label["resume_id"] in resumes]
        if not labels:
            cli.error("No independent validation pairs are available")
        sample = rng.sample(labels, min(args.limit, len(labels)))
        cases = []
        for label in sample:
            row = resumes[label["resume_id"]]
            profile = Profile(row["category"], skills=extract_skills(row["text"]))
            cases.append((profile, label["job_id"], json.loads(label["completion"])["score"]))
    modes = {"base": "", **({"adapter": str(args.adapter)} if args.adapter else {})}
    for name, path in modes.items():
        with patch.dict(os.environ, {"HIREMIND_ADAPTER_DIR": path, "HIREMIND_ADAPTER_ROLES": args.role}):
            result = eval_searcher(profiles) if args.role == "searcher" else eval_critic(cases)
            print(name, json.dumps(result), flush=True)


if __name__ == "__main__":
    main()
